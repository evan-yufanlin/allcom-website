export interface GenSet {
  series: string;
  model: string;
  engine: string;
  /** 環保（排放）等級，型錄未列為空字串 */
  emission: string;
  standbyKw: number;
  standbyKva: number;
  primeKw: number | null;
  primeKva: number | null;
  /** [長, 寬, 高]（mm）；型錄未列為 null */
  size: [number, number, number] | null;
  weight: number | null;
  /** 機組附油箱容量（L，東元）；型錄未列為 null */
  baseTank: number | null;
  /** 滿載（Standby）耗油量（L/h，中興）；型錄未列為 null */
  fuel: number | null;
}

// ---- 東元：[型號, 引擎, Standby kVA, kW, Prime kVA, kW, 長, 寬, 高, 重量, 油箱] ----
type TecoRow = [string, string, number, number, number | null, number | null, number, number, number, number, number | null];

function teco(series: string, emission: string, rows: TecoRow[]): GenSet[] {
  return rows.map(([model, engine, sva, skw, pva, pkw, l, w, h, kg, tank]) => ({
    series,
    model,
    engine,
    emission,
    standbyKw: skw,
    standbyKva: sva,
    primeKw: pkw,
    primeKva: pva,
    size: [l, w, h],
    weight: kg,
    baseTank: tank,
    fuel: null,
  }));
}

