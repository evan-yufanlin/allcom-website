type ChemRow = [string, string, string, number, number, number | null, number | null, number];

function chem(series: string, rows: ChemRow[], dims: Record<string, [number, number, number, number]>): GenSet[] {
  return rows.map(([model, engine, emission, skw, sva, pkw, pva, fuel]) => {
    const d = dims[model];
    return {
      series,
      model,
      engine,
      emission,
      standbyKw: skw,
      standbyKva: sva,
      primeKw: pkw,
      primeKva: pva,
      size: d ? [d[0], d[1], d[2]] : null,
      weight: d ? d[3] : null,
      baseTank: null,
      fuel,
    };
  });
}

